function CardWrap({
  product,
  heightClass,
  children,
}: {
  product: Product;
  heightClass: string;
  children: React.ReactNode;
}) {
  const reduce = useReducedMotion();
  const verdictColor = VERDICT_COLOR[product.verdict];
  return (
    <motion.article
      variants={STAGGER_ITEM_VARIANTS}
      whileHover={reduce ? undefined : { y: -6, scale: 1.015 }}
      transition={{ type: "spring", stiffness: 220, damping: 22 }}
      className={cn(
        "group relative overflow-hidden rounded-[24px] border border-border-soft bg-surface/70 backdrop-blur-md transition-shadow",
        heightClass,
      )}
      style={{
        boxShadow: `0 0 0 1px ${verdictColor}22, 0 18px 40px -24px ${verdictColor}55`,
      }}
    >
      <Link
        href={`/product/${product.id}`}
        aria-label={`Open ${product.name}`}
        className="absolute inset-0 z-0"
      />
      <div className="relative z-10 h-full">{children}</div>
    </motion.article>
  );
}

function MetadataRow({ product, compact }: { product: Product; compact?: boolean }) {
  const niche = NICHES[product.category];
  const country = COUNTRIES[product.targetCountry];
  return (
    <div
      className={cn(
        "flex flex-wrap items-center gap-x-3 gap-y-1 text-[11px] text-text-muted",
        compact && "gap-x-2",
      )}
    >
      <span className="flex items-center gap-1.5">
        <span
          className="h-1.5 w-1.5 rounded-full"
          style={{ backgroundColor: niche?.color ?? "#A788FF" }}
        />
        <span>{niche?.label ?? product.category}</span>
      </span>
      {!compact && <span aria-hidden>·</span>}
      <span>
        {country?.flag ?? "🌐"} {country?.code ?? product.targetCountry}
      </span>
      <span aria-hidden>·</span>
      <span
        className="font-mono font-medium"
        style={{ color: VERDICT_COLOR[product.verdict] }}
      >
        <ScoreNumber value={product.sellScore} className="font-mono" /> · {product.verdict.toUpperCase()}
      </span>
    </div>
  );
}

function FavoriteHeart({ productId }: { productId: string }) {
  const favorites = useProductStore((s) => s.favorites);
  const toggleFavorite = useProductStore((s) => s.toggleFavorite);
  const fav = favorites instanceof Set ? favorites.has(productId) : false;
  return (
    <button
      type="button"
      onClick={(e) => {
        e.preventDefault();
        e.stopPropagation();
        toggleFavorite(productId);
      }}
      aria-label={fav ? "Unfavorite" : "Favorite"}
      className="absolute right-3 top-3 z-20 inline-flex h-9 w-9 items-center justify-center rounded-full bg-white/80 text-text backdrop-blur-md transition-all hover:scale-110 dark:bg-black/40 dark:text-white"
    >
      <motion.span
        animate={{ scale: fav ? [1, 1.3, 1] : 1 }}
        transition={{ duration: 0.4, ease: [0.22, 1, 0.36, 1] }}
      >
        <Heart
          className={cn("h-4 w-4", fav && "fill-aurora-pink text-aurora-pink")}
        />
      </motion.span>
    </button>
  );
}

function defaultPitch(p: Product): string {
  const niche = NICHES[p.category]?.label.toLowerCase();
  const country = COUNTRIES[p.targetCountry]?.name;
  return `Scored ${p.sellScore} against ${p.verdict.toUpperCase()} threshold, with ${niche ?? "category"} demand signal and ${country ?? "target market"} fit doing most of the work.`;
}

