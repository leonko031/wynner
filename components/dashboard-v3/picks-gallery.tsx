const VERDICT_COLOR: Record<Verdict, string> = {
  go: "#3DD68C",
  test: "#FFAB40",
  risky: "#FF7E5F",
  skip: "#FF5C7C",
};

type GalleryView = "editorial" | "grid" | "compact";

type Props = {
  /** Curated picks for the day. Already sorted high→low; we slice into rows. */
  picks: Product[];
  /** Editorial title generated by Gemini, or a graceful fallback. */
  editorialTitle: string;
  sectionId: string;
  /** Optional 2-sentence "pitch" for pick #1, generated by Gemini in the briefing. */
  pickOnePitch?: string;
};

export function PicksGallery({
  picks,
  editorialTitle,
  sectionId,
  pickOnePitch,
}: Props) {
  const [view, setView] = useState<GalleryView>("editorial");
  const headliner = picks[0];
  const pair = picks.slice(1, 3);
  const quartet = picks.slice(3, 7);
  const tail = picks.slice(7);

  return (
    <section className="pt-32 md:pt-40">
      <div className="mx-auto w-full max-w-7xl px-6 md:px-12">
        <div className="relative">
          <SectionHeader
            id={sectionId}
            kicker="TODAY'S PICKS · CURATED FOR YOU"
            headline={editorialTitle}
            subHeadline={`${picks.length} product${picks.length === 1 ? "" : "s"} our AI thinks you should look at today`}
          />
          <div className="absolute right-0 top-3 hidden md:block">
            <ViewSwitcher view={view} onChange={setView} />
          </div>
        </div>

        {picks.length === 0 ? (
          <EmptyPicks />
        ) : view === "grid" ? (
          <UniformGrid picks={picks} />
        ) : view === "compact" ? (
          <CompactList picks={picks} />
        ) : (
          <StaggerGrid className="space-y-6">
            {headliner && (
              <StaggerItem>
                <HeadlinerCard product={headliner} pitch={pickOnePitch} />
              </StaggerItem>
            )}
            {pair.length > 0 && (
              <div className="grid grid-cols-1 gap-6 md:grid-cols-2">
                {pair.map((p) => (
                  <StaggerItem key={p.id}>
                    <PairCard product={p} />
                  </StaggerItem>
                ))}
              </div>
            )}
            {quartet.length > 0 && (
              <div className="grid grid-cols-2 gap-4 md:grid-cols-4">
                {quartet.map((p) => (
                  <StaggerItem key={p.id}>
                    <QuartetCard product={p} />
                  </StaggerItem>
                ))}
              </div>
            )}
            {tail.length > 0 && (
              <StaggerItem>
                <TailScroll picks={tail} />
              </StaggerItem>
            )}
          </StaggerGrid>
        )}
      </div>
    </section>
  );
}

/* -------------------------------------------------------------------------- */

function ViewSwitcher({
  view,
  onChange,
}: {
  view: GalleryView;
  onChange: (v: GalleryView) => void;
}) {
  return (
    <div className="inline-flex items-center gap-1 rounded-full bg-surface/70 p-1 backdrop-blur-md">
      <ViewBtn current={view} value="editorial" onClick={onChange} icon={Newspaper} />
      <ViewBtn current={view} value="grid" onClick={onChange} icon={LayoutGrid} />
      <ViewBtn current={view} value="compact" onClick={onChange} icon={List} />
    </div>
  );
}

function ViewBtn({
  current,
  value,
  onClick,
  icon: Icon,
}: {
  current: GalleryView;
  value: GalleryView;
  onClick: (v: GalleryView) => void;
  icon: typeof Newspaper;
}) {
  const active = current === value;
  return (
    <button
      type="button"
      aria-label={value}
      onClick={() => onClick(value)}
      className={cn(
        "inline-flex h-7 w-7 items-center justify-center rounded-full transition-all",
        active
          ? "bg-surface text-text shadow-sm"
          : "text-text-muted hover:text-text",
      )}
    >
      <Icon className="h-3.5 w-3.5" />
    </button>
  );
}

/* -------------------------------------------------------------------------- */

function HeadlinerCard({ product, pitch }: { product: Product; pitch?: string }) {
  return (
    <CardWrap product={product} heightClass="h-auto md:h-96">
      <div className="grid h-full grid-cols-1 md:grid-cols-[60%_40%]">
        <div className="relative h-64 md:h-full">
          {product.image && (
            <Image
              src={product.image}
              alt={product.name}
              fill
              sizes="(max-width: 768px) 100vw, 60vw"
              className="object-cover"
            />
          )}
          <FavoriteHeart productId={product.id} />
        </div>
        <div className="flex flex-col justify-between p-6 md:p-8">
          <div>
            <span className="font-mono text-[10px] uppercase tracking-[0.2em] text-text-dim">
              Pick #1
            </span>
            <h3 className="mt-3 font-serif text-3xl leading-tight text-text md:text-4xl">
              {product.name}
            </h3>
            <p className="mt-3 text-sm leading-relaxed text-text-muted md:text-[15px]">
              {pitch ?? defaultPitch(product)}
            </p>
          </div>
          <div className="mt-6 space-y-3">
            <MetadataRow product={product} />
            <Link
              href={`/product/${product.id}`}
              className="inline-flex items-center gap-1.5 text-sm font-medium text-aurora-purple hover:text-aurora-pink"
            >
              Open dossier <ArrowRight className="h-3.5 w-3.5" />
            </Link>
          </div>
        </div>
      </div>
    </CardWrap>
  );
}

