"use client";

import { motion, useReducedMotion } from "framer-motion";
import { ArrowRight, Heart, LayoutGrid, List, Newspaper } from "lucide-react";
import Image from "next/image";
import Link from "next/link";
import { useState } from "react";
import { ScoreNumber } from "@/components/animated/score-number";
import { SectionHeader, STAGGER_ITEM_VARIANTS, StaggerGrid, StaggerItem } from "./editorial-primitives";
import {
  Tooltip,
  TooltipContent,
  TooltipTrigger,
} from "@/components/ui/tooltip";
import { NICHES } from "@/lib/data/niches";
