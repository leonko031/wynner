function UniformGrid({ picks }: { picks: Product[] }) {
  return (
    <StaggerGrid className="grid grid-cols-2 gap-4 md:grid-cols-4">
      {picks.map((p) => (
        <StaggerItem key={p.id}>
          <QuartetCard product={p} />
        </StaggerItem>
      ))}
    </StaggerGrid>
  );
}

function CompactList({ picks }: { picks: Product[] }) {
  return (
    <StaggerGrid className="divide-y divide-border-soft overflow-hidden rounded-3xl border border-border-soft bg-surface/70 backdrop-blur-md">
      {picks.map((p) => (
        <StaggerItem key={p.id} as="div">
          <Link
            href={`/product/${p.id}`}
            className="grid grid-cols-[60px_1fr_120px_80px] items-center gap-4 px-4 py-3 transition-colors hover:bg-surface/40"
          >
            <div className="relative h-12 w-12 overflow-hidden rounded-md bg-surface-elevated">
              {p.image && (
                <Image src={p.image} alt={p.name} fill sizes="48px" className="object-cover" />
              )}
            </div>
            <div className="min-w-0">
              <div className="truncate text-sm text-text">{p.name}</div>
              <div className="font-mono text-[10px] text-text-dim">
                {NICHES[p.category]?.label} · {COUNTRIES[p.targetCountry]?.flag}
              </div>
            </div>
            <span className="font-mono text-xs tabular-nums text-text-muted">
              {p.verdict.toUpperCase()}
            </span>
            <span
              className="text-right font-mono text-sm font-medium tabular-nums"
              style={{ color: VERDICT_COLOR[p.verdict] }}
            >
              {p.sellScore}
            </span>
          </Link>
        </StaggerItem>
      ))}
    </StaggerGrid>
  );
}

